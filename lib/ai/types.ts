/**
 * AI provider types and interfaces.
 * Abstraction layer for AI response generation.
 */

import type { Message, MessageSource } from "@/types";

/** Configuration for an AI provider. */
export interface AIProviderConfig {
  /** Display name of the provider. */
  name: string;
  /** Whether the provider is a mock/demo. */
  isMock: boolean;
  /** Maximum context length in characters. */
  maxContextLength?: number;
}

/** Request payload for generating a response. */
export interface AIRequest {
  /** The user's message. */
  userMessage: string;
  /** Previous messages for context. */
  conversationHistory: Message[];
  /** Knowledge context retrieved from the knowledge engine. */
  knowledgeContext?: string;
  /** System prompt. */
  systemPrompt: string;
}

/** Response from an AI provider. */
export interface AIResponse {
  /** Generated response content (Markdown). */
  content: string;
  /** Sources referenced in the response. */
  sources: MessageSource[];
  /** Provider metadata. */
  provider: string;
  /** Whether this was generated by a mock provider. */
  isMock: boolean;
}

/**
 * Abstract AI provider interface.
 * Implement this for each AI backend (OpenAI, Google AI, mock, etc.).
 */
export interface AIProvider {
  /** Provider configuration. */
  config: AIProviderConfig;
  /** Generate a response. */
  generateResponse(request: AIRequest): Promise<AIResponse>;
}

